#include <stdio.h>
int main() {
    /*Operação de verificação de impar e par usando a estrutura if e else if*/

    int numero1 = 9;
    int numero2 = 21;


    if (numero1 %2 == 0) 
        {printf("O numero1 é par\n");}
         else if (numero1 %2 != 0)
              {printf("O numero1 é impar\n");}

    if (numero2 %2 == 0) 
        {printf("O numero2 é par\n");}
         else if (numero2 %2 != 0)
              {printf("O numero2 é impar\n");}
}
